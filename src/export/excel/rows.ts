  r('cf_pbt', 'Profit before tax', 'egp', '[pbt]');
  r('cf_dep', 'Depreciation', 'egp', '[dep]');
  r('cf_amort', 'Amortization', 'egp', '[amort]');
  r('cf_prov_rev', 'Provisions no longer required', 'egp', '-[d_prov_reversed]');
  r('cf_prov_formed', 'Provisions formed', 'egp', '[d_prov_formed]');
  r('cf_ebo_cost', 'Employee benefit obligations', 'egp', '[d_ebo_service]');
  r('cf_cap_losses', 'Capital losses', 'egp', '0');
  r('cf_cap_gains', 'Capital gains', 'egp', '-[cap_gains]');
  r('cf_other_adj', 'Adjustment on other revenues', 'egp', '0');
  r('cf_ecl', 'ECL (reversal) / charge', 'egp', '-[d_ecl]');
  r('cf_impairment', 'Impairment (reversal) / charge', 'egp', '-[d_impairment]');
  r('cf_net_fin', 'Net finance (income) and cost', 'egp', '[fin_costs]-[fin_income]');
  r('cf_fx_unreal', 'Unrealized FX loss / (gain)', 'egp', '-[fx_unreal]');
  r('cf_before_wc', 'Subtotal before working capital', 'egp', 'SUM([cf_pbt]:[cf_fx_unreal])', undefined, true);
