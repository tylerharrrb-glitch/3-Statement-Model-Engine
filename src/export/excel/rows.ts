  r('cf_cust_adv', 'Customer advances', 'egp', '[cust_adv]-[cust_adv@-1]');
  r('cf_prov_used', 'Provisions used', 'egp', '-[d_prov_used]');
  r('cf_before_dist', 'Cash from operations before distributions and taxes', 'egp', '[cf_before_wc]+SUM([cf_ofa]:[cf_prov_used])', undefined, true);
