  r('total_nca', 'Total non-current assets', 'egp', `SUM([fixed_assets]:[ofa])`, 'same', true);
  r('inventory', 'Inventory', 'egp', '[d_dio]*[cogs]/365');
  r('ar', 'Accounts receivable', 'egp', '[d_dso]*[revenue]/365');
  r('inv_cur', 'Amortized-cost investments, current', 'egp', '[inv_cur@-1]+[d_inv_cur_net]+[fxg_inv_cur]');
