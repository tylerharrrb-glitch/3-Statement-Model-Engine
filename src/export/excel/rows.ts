  r('debt_cur', 'Borrowings, current', 'egp', '[debt_total]*[d_debt_cur_share]', 'ZERO');
  r('ap', 'Trade payables', 'egp', '[d_dpo]*[cogs]/365');
  r('creditors', 'Creditors and other credit balances', 'egp', '[d_creditors_pct]*[revenue]');
  r('dividends_payable', 'Dividends payable', 'egp', '[dividends_payable@-1]+[declared_dividends]-[dividends_paid]', 'ZERO');
