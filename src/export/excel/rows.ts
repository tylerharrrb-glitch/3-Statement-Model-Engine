  r('cash', 'Cash and cash equivalents', 'egp', '[cf_close]');
  r('total_ca', 'Total current assets', 'egp', 'SUM([inventory]:[cash])', 'same', true);
  r('total_assets', 'Total assets', 'egp', '[total_nca]+[total_ca]', 'same', true);
  r('capital', 'Issued capital', 'egp', '[capital@-1]+[bonus_total]');
  r('legal_reserve', 'Legal reserve', 'egp', '[legal_reserve@-1]+[s_lr_transfer]');
  r('general_reserve', 'General reserve', 'egp', '[general_reserve@-1]-[d_bonus_res]');
  r('merger_reserve', 'Result of merging process', 'egp', '[merger_reserve@-1]');
  r('re', 'Retained earnings', 'egp', '[s_re]');
