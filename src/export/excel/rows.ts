// The Excel model as formula templates. Syntax: [id] same column, [id@-1] prior column,
// [id@first] first forecast column, [id@last] last column, NAME = a named scalar on Inputs.
// This table drives the workbook, the on-screen formula text and docs/METHODOLOGY.md.
import type { ModelInputs } from '../../engine/types';
import { CS_BS, CS_IS } from '../../engine/outputs/index';

export type Fmt = 'egp' | 'pct' | 'x' | 'num' | 'fx' | 'days' | 'ps' | 'int' | 'usd';
export type SheetName = 'Model' | 'Schedules' | 'Ratios';

export interface RowSpec {
  id: string;
  label: string;
  fmt: Fmt;
  sheet: SheetName;
  section: string;
  /** Forecast formula. Absent = historical-only. */
  f?: string;
  /** Historical formula. Absent = link to the Inputs line when loaded, else blank. */
  h?: string;
  total?: boolean;
  /** True when the value comes from Inputs in historical years. */
  note?: string;
}

const safe = (a: string, b: string) => `IF(${b}=0,0,${a}/${b})`;
const R: RowSpec[] = [];
let sheet: SheetName = 'Model';
let section = '';
const sec = (sh: SheetName, name: string) => { sheet = sh; section = name; };
const r = (id: string, label: string, fmt: Fmt, f?: string, h?: string, total = false) => R.push({ id, label, fmt, sheet, section, f, h, total });
const SUM = (ids: string[]) => ids.map(i => `[${i}]`).join('+');

