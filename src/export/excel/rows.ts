  R.length = 0;
  // ---------- Income statement ----------
  sec('Model', 'Income statement');
  r('rev_export', 'Net sales - export', 'egp', '[s_rev_export]');
  r('rev_domestic', 'Net sales - domestic', 'egp', '[s_revenue]-[s_rev_export]');
  r('revenue', 'Net sales', 'egp', '[s_revenue]', '[rev_export]+[rev_domestic]', true);
  r('cogs', 'Cost of sales', 'egp', '[s_cogs]');
  r('gross_profit', 'Gross profit', 'egp', '[revenue]-[cogs]', 'same', true);
  r('other_income_total', 'Other income', 'egp', '[d_other_income]+[d_prov_reversed]');
  r('selling', 'Selling and marketing', 'egp', '[s_selling]');
  r('ga', 'General and administrative', 'egp', '[ga_cash]+[amort]+[depr_ga]');
  r('cap_gains', 'Capital gains', 'egp', '[d_disposal_proceeds]-[d_disposal_nbv]');
  r('other_exp_total', 'Other expenses', 'egp', '[d_other_exp]+[d_prov_formed]');
  r('impairment', 'Impairment reversal', 'egp', '[d_impairment]');
  r('ecl', 'ECL reversal / (charge)', 'egp', '[d_ecl]');
  r('op_profit', 'Operating profit', 'egp', '[gross_profit]+[other_income_total]-[selling]-[ga]+[cap_gains]-[other_exp_total]+[impairment]+[ecl]', 'same', true);
  r('fin_income', 'Finance income', 'egp', '[s_fin_income]');
  r('lease_int', 'Finance cost - lease interest', 'egp', '[s_lease_int]');
  r('ebo_int', 'Finance cost - employee benefit interest', 'egp', '[s_ebo_int]');
  r('debt_int', 'Finance cost - borrowings', 'egp', '[s_debt_int]', 'ZERO');
  r('fin_costs', 'Finance costs', 'egp', '[lease_int]+[ebo_int]+[debt_int]', 'same', true);
  r('fx_line', 'FX translation gain / (loss)', 'egp', '[fx_unreal]+[fxg_wc]');
  r('pbt', 'Profit before tax', 'egp', '[op_profit]+[fin_income]-[fin_costs]+[fx_line]', 'same', true);
  r('current_tax', 'Current tax', 'egp', '[s_current_tax]');
  r('deferred_tax', 'Deferred tax expense / (income)', 'egp', '[dtl_mov_ppe]+[dtl_mov_fx]');
  r('net_profit', 'Net profit', 'egp', '[pbt]-[current_tax]-[deferred_tax]', 'same', true);
  r('oci_gross', 'OCI actuarial, gross', 'egp', '[d_oci_gross]');
  r('oci_dt', 'OCI deferred tax', 'egp', '-[d_oci_gross]*TAX_RATE');
  r('oci_net', 'OCI, net of deferred tax', 'egp', '[oci_gross]+[oci_dt]', 'same', true);
  r('dep', 'Memo: depreciation', 'egp', '[s_dep]');
  r('amort', 'Memo: amortization', 'egp', '[oa_amort]+[rou_amort]');
  r('gas_cost', 'Memo: natural gas in cost of sales', 'egp', '[s_gas_cost]');
  r('prov_reversed', 'Memo: provisions no longer required', 'egp', '[d_prov_reversed]');
  r('effective_tax', 'Effective tax rate', 'pct', safe('([current_tax]+[deferred_tax])', '[pbt]'));

  // ---------- Balance sheet ----------
  sec('Model', 'Balance sheet');
  r('fixed_assets', 'Fixed assets and PUC', 'egp', '[ppe_nbv]+[puc]');
  r('other_assets', 'Other assets and PUC', 'egp', '[other_assets@-1]+[d_oa_add]-[oa_amort]');
  r('rou', 'Right-of-use assets', 'egp', '[rou@-1]+[d_rou_new]-[rou_amort]');
  r('associates', 'Investments in associates', 'egp', '[associates@-1]+[d_assoc_mov]');
  r('inv_nc', 'Amortized-cost investments, non-current', 'egp', '[inv_nc@-1]+[d_inv_nc_net]+[fxg_inv_nc]');
  r('ofa', 'Other financial assets', 'egp', '[ofa@-1]+[d_ofa_mov]+[fxg_ofa]');
