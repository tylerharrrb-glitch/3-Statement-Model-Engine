  r('cf_tax_paid', 'Income taxes paid', 'egp', '-[tax_paid]');
  r('cf_ebo_paid', 'Employee benefits paid', 'egp', '-[d_ebo_paid]');
  r('cf_int_rec_op', 'Interest received (operating policy)', 'egp', '[fin_income]*INT_REC_OP');
  r('cf_int_paid_op', 'Interest paid (operating policy)', 'egp', '-[debt_int]*INT_PAID_OP');
  r('cf_cfo', 'Net cash from operating activities', 'egp', '[cf_before_dist]+SUM([cf_dist_op]:[cf_int_paid_op])', undefined, true);
  r('cf_int_rec_inv', 'Interest received', 'egp', '[fin_income]*(1-INT_REC_OP)');
  r('cf_assoc', 'Investment in associates', 'egp', '-[d_assoc_mov]');
  r('cf_fvtpl', 'FVTPL, net', 'egp', '-[d_fvtpl_net]');
  r('cf_ac', 'Amortized-cost investments, net', 'egp', '-([d_inv_nc_net]+[d_inv_cur_net])');
  r('cf_proceeds', 'Proceeds from asset sales', 'egp', '[d_disposal_proceeds]');
  r('cf_capex', 'Capital expenditure', 'egp', '-[capex_total]');
  r('cf_oa_add', 'Other assets additions', 'egp', '-[d_oa_add]');
  r('cf_cfi', 'Net cash from investing activities', 'egp', 'SUM([cf_int_rec_inv]:[cf_oa_add])', undefined, true);
  r('cf_div', 'Dividends to shareholders', 'egp', '-[dividends_paid]');
  r('cf_leases', 'Lease payments', 'egp', '-[d_lease_pay]');
  r('cf_dist_fin', 'Distributions (financing policy)', 'egp', '-[distributions]*(1-DIST_OP)');
  r('cf_borrow', 'Borrowings drawn', 'egp', '[debt_borrow]');
  r('cf_repay', 'Borrowings repaid', 'egp', '-[debt_repay_sched]-[sweep_total]');
  r('cf_revolver', 'Revolver, net', 'egp', '[rev_net]');
  r('cf_int_paid_fin', 'Interest paid (financing policy)', 'egp', '-[debt_int]*(1-INT_PAID_OP)');
  r('cf_cff', 'Net cash from financing activities', 'egp', 'SUM([cf_div]:[cf_int_paid_fin])', undefined, true);
  r('cf_net', 'Net change in cash', 'egp', '[cf_cfo]+[cf_cfi]+[cf_cff]', undefined, true);
  r('cf_fx_cash', 'FX effect on cash', 'egp', '[fxg_cash]');
  r('cf_ecl_cash', 'ECL on cash', 'egp', '0');
  r('cf_open', 'Opening cash', 'egp', '[cash@-1]');
  r('cf_close', 'Closing cash', 'egp', '[cf_open]+[cf_net]+[cf_fx_cash]+[cf_ecl_cash]', '[cash]', true);

